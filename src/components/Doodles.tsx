type Props = {
  name: DoodleName;
  className?: string;
  // CSS genişliği, ör. "2.2rem" veya "120px"
  width?: string;
  // Çizilme gecikmesi (ms)
  delay?: number;
  // Havada hafifçe süzülsün mü
  float?: boolean;
  // Yatayda esneyebilsin (alt çizgi gibi)
  stretch?: boolean;
};

export function Doodle({
  name,
  className = "",
  width,
  delay = 0,
  float = false,
  stretch = false,
}: Props) {
  const shape = shapes[name];
  const classes = `art dd dd-${name}${float ? " float" : ""}${className ? ` ${className}` : ""}`;

  return (
    <svg
      className={classes}
      viewBox={shape.viewBox}
      preserveAspectRatio={stretch ? "none" : undefined}
      aria-hidden="true"
      focusable="false"
      data-reveal
      style={{ "--w": width, "--s": `${delay}ms` } as CSSProperties}
    >
      {shape.body}
    </svg>
  );
}
